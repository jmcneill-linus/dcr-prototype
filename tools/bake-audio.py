#!/usr/bin/env python3
"""Bake the prototype's audio scripts into m4a files + a timing manifest.

Generates one file per distinct Audio.speak() utterance (keys must stay exact
string matches with the texts in js/screens.js), converts to AAC, measures real
durations, and distributes per-word karaoke offsets char-weighted across the
audible span. Rerun after any script/voice change:

    python3 tools/bake-audio.py

Requires macOS `say` + `afconvert` + `afinfo` and the voice below installed
(System Settings > Accessibility > Spoken Content > Manage Voices).
"""
import json
import os
import re
import subprocess
import sys

VOICE = "Evan (Enhanced)"  # Justin's pick, 2026-08-15
TAIL_MS = 350              # breath at the end of a file that carries no words

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "assets", "audio")
MANIFEST = os.path.join(ROOT, "js", "audio-manifest.js")

# (file slug, exact Audio.speak() text, optional say-text override)
# recallWords: real cadence has long gaps between words; [[slnc]] adds them.
UTTERANCES = [
    ("pencil-heading", "To get started, let's make sure your pencil works.", None),
    ("pencil-draw", "Draw a line or mark in the box below.", None),
    ("welcome-1", "We're going to complete a few tasks to check your memory and thinking.", None),
    ("welcome-2", "Make sure you are in a quiet spot. Once we begin, try to stay focused on the tasks. Do your best on your own without asking for help.", None),
    ("welcome-3", "When the activity starts, we'll go from one task to the next without pausing.", None),
    ("welcome-4", "When you finish a task, tap Done.", None),
    ("ir-inst-1", "You will hear three words read aloud. After you hear all three words, you'll be asked to repeat them out loud.", None),
    ("ir-inst-2", "Try to remember them. You'll be asked about these three words again later.", None),
    ("recall-words", "Apple. Table. Penny.", "Apple. [[slnc 1200]] Table. [[slnc 1200]] Penny."),
    ("ir-recording", "Please say the words out loud now.", None),
    ("dr-recording", "Please say the three words out loud you were asked to remember.", None),
    ("finished-tap-done", "When you're finished, tap the Done button.", None),
    ("clock-command", "Please draw the face of a clock with all of the numbers, and set the time to ten minutes after eleven.", None),
    ("clock-copy", "Please copy the figure in the space below.", None),
]


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"FAILED: {' '.join(cmd)}\n{r.stderr}")
    return r.stdout


def duration_ms(path):
    out = run(["afinfo", path])
    m = re.search(r"estimated duration:\s*([\d.]+)\s*sec", out)
    if not m:
        sys.exit(f"no duration in afinfo output for {path}")
    return round(float(m.group(1)) * 1000)


def word_offsets(text, dur, even=False):
    words = [w for w in re.split(r"\s+", text) if w]
    audible = max(dur - TAIL_MS, 1)
    if even:  # long inter-word silences make char-weighting wrong
        return [round(i * dur / len(words)) for i in range(len(words))]
    total = sum(len(w) for w in words) or 1
    offsets, acc = [], 0
    for w in words:
        offsets.append(round(audible * acc / total))
        acc += len(w)
    return offsets


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    entries = {}
    for slug, text, say_text in UTTERANCES:
        aiff = os.path.join(OUT_DIR, f"{slug}.aiff")
        m4a = os.path.join(OUT_DIR, f"{slug}.m4a")
        run(["say", "-v", VOICE, "-o", aiff, say_text or text])
        run(["afconvert", "-f", "m4af", "-d", "aac", aiff, m4a])
        os.remove(aiff)
        dur = duration_ms(m4a)
        entries[text] = {
            "src": f"assets/audio/{slug}.m4a",
            "dur": dur,
            "words": word_offsets(text, dur, even=slug == "recall-words"),
        }
        print(f"  {slug}.m4a  {dur / 1000:.1f}s")

    body = json.dumps(entries, indent=2, ensure_ascii=False)
    with open(MANIFEST, "w") as f:
        f.write(
            "// GENERATED by tools/bake-audio.py. Do not hand-edit; rerun the bake\n"
            f"// after any script or voice change. Voice: {VOICE}.\n"
            f"export const MANIFEST = {body};\n"
        )
    print(f"wrote {len(entries)} entries -> {os.path.relpath(MANIFEST, ROOT)}")


if __name__ == "__main__":
    main()
